UPDATE core.changesets t SET created_by_user_id = u.id FROM core.users u WHERE u.username = t.created_by;
UPDATE core.nodes t SET created_by_user_id = u.id FROM core.users u WHERE u.username = t.created_by;
UPDATE core.nodes t SET updated_by_user_id = u.id FROM core.users u WHERE u.username = t.updated_by;
UPDATE core.ways t SET created_by_user_id = u.id FROM core.users u WHERE u.username = t.created_by;
