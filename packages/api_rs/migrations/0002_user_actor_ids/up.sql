-- Replace legacy username actor columns with stable user references in one
-- coordinated cutover.  The temporary columns make the backfill atomic.
CREATE TABLE core.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO core.users (username)
SELECT DISTINCT username
FROM (
  SELECT created_by AS username FROM core.changesets
  UNION SELECT created_by FROM core.nodes
  UNION SELECT updated_by FROM core.nodes
  UNION SELECT created_by FROM core.ways
  UNION SELECT updated_by FROM core.ways
  UNION SELECT created_by FROM core.relations
  UNION SELECT updated_by FROM core.relations
  UNION SELECT staged_by FROM draft.nodes
  UNION SELECT staged_by FROM draft.ways
  UNION SELECT staged_by FROM draft.relations
  UNION
    SELECT snapshot->>'createdBy'
    FROM history.node_versions
    WHERE jsonb_typeof(snapshot->'createdBy') = 'string'
  UNION
    SELECT snapshot->>'updatedBy'
    FROM history.node_versions
    WHERE jsonb_typeof(snapshot->'updatedBy') = 'string'
  UNION
    SELECT snapshot->>'createdBy'
    FROM history.way_versions
    WHERE jsonb_typeof(snapshot->'createdBy') = 'string'
  UNION
    SELECT snapshot->>'updatedBy'
    FROM history.way_versions
    WHERE jsonb_typeof(snapshot->'updatedBy') = 'string'
  UNION
    SELECT snapshot->>'createdBy'
    FROM history.relation_versions
    WHERE jsonb_typeof(snapshot->'createdBy') = 'string'
  UNION
    SELECT snapshot->>'updatedBy'
    FROM history.relation_versions
    WHERE jsonb_typeof(snapshot->'updatedBy') = 'string'
) actors
WHERE username IS NOT NULL;

ALTER TABLE core.changesets ADD COLUMN created_by_user_id bigint;
ALTER TABLE core.nodes ADD COLUMN created_by_user_id bigint, ADD COLUMN updated_by_user_id bigint;
