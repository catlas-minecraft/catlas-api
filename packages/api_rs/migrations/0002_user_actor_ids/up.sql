-- History snapshots are immutable records, so retain each actor identity as
-- an ID while dropping the denormalized username.  Each key is converted
-- independently so partial snapshots are handled deterministically.
UPDATE history.node_versions h
SET snapshot = jsonb_set(h.snapshot - 'createdBy', '{createdByUserId}', to_jsonb(u.id), true)
FROM core.users u
WHERE jsonb_typeof(h.snapshot->'createdBy') = 'string'
  AND h.snapshot->>'createdBy' = u.username;
UPDATE history.node_versions h
SET snapshot = jsonb_set(h.snapshot - 'updatedBy', '{updatedByUserId}', to_jsonb(u.id), true)
FROM core.users u
WHERE jsonb_typeof(h.snapshot->'updatedBy') = 'string'
  AND h.snapshot->>'updatedBy' = u.username;
UPDATE history.way_versions h
SET snapshot = jsonb_set(h.snapshot - 'createdBy', '{createdByUserId}', to_jsonb(u.id), true)
FROM core.users u
WHERE jsonb_typeof(h.snapshot->'createdBy') = 'string'
  AND h.snapshot->>'createdBy' = u.username;
UPDATE history.way_versions h
SET snapshot = jsonb_set(h.snapshot - 'updatedBy', '{updatedByUserId}', to_jsonb(u.id), true)
FROM core.users u
WHERE jsonb_typeof(h.snapshot->'updatedBy') = 'string'
  AND h.snapshot->>'updatedBy' = u.username;
UPDATE history.relation_versions h
SET snapshot = jsonb_set(h.snapshot - 'createdBy', '{createdByUserId}', to_jsonb(u.id), true)
FROM core.users u
WHERE jsonb_typeof(h.snapshot->'createdBy') = 'string'
  AND h.snapshot->>'createdBy' = u.username;
UPDATE history.relation_versions h
SET snapshot = jsonb_set(h.snapshot - 'updatedBy', '{updatedByUserId}', to_jsonb(u.id), true)
FROM core.users u
WHERE jsonb_typeof(h.snapshot->'updatedBy') = 'string'
  AND h.snapshot->>'updatedBy' = u.username;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM history.node_versions
    WHERE snapshot ? 'createdBy' OR snapshot ? 'updatedBy'
      OR jsonb_typeof(snapshot->'createdByUserId') = 'string'
      OR jsonb_typeof(snapshot->'updatedByUserId') = 'string'
  ) OR EXISTS (
    SELECT 1 FROM history.way_versions
    WHERE snapshot ? 'createdBy' OR snapshot ? 'updatedBy'
      OR jsonb_typeof(snapshot->'createdByUserId') = 'string'
      OR jsonb_typeof(snapshot->'updatedByUserId') = 'string'
  ) OR EXISTS (
    SELECT 1 FROM history.relation_versions
    WHERE snapshot ? 'createdBy' OR snapshot ? 'updatedBy'
      OR jsonb_typeof(snapshot->'createdByUserId') = 'string'
      OR jsonb_typeof(snapshot->'updatedByUserId') = 'string'
  ) THEN
    RAISE EXCEPTION 'history actor migration left an unmapped legacy actor';
  END IF;
END $$;
