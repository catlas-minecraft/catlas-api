UPDATE core.relations t SET created_by_user_id = u.id FROM core.users u WHERE u.username = t.created_by;
UPDATE core.relations t SET updated_by_user_id = u.id FROM core.users u WHERE u.username = t.updated_by;
UPDATE draft.nodes t SET staged_by_user_id = u.id FROM core.users u WHERE u.username = t.staged_by;
UPDATE draft.ways t SET staged_by_user_id = u.id FROM core.users u WHERE u.username = t.staged_by;
