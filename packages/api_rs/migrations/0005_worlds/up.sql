CREATE OR REPLACE FUNCTION core.catlas_relation_member_same_world()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.member_type = 'node' AND NOT EXISTS (
      SELECT 1 FROM core.nodes WHERE id = NEW.member_id AND world_id = NEW.world_id
    )) OR (NEW.member_type = 'way' AND NOT EXISTS (
      SELECT 1 FROM core.ways WHERE id = NEW.member_id AND world_id = NEW.world_id
    )) OR (NEW.member_type = 'relation' AND NOT EXISTS (
      SELECT 1 FROM core.relations WHERE id = NEW.member_id AND world_id = NEW.world_id
    )) THEN
    RAISE EXCEPTION 'relation member belongs to a different world';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER relation_members_same_world
  BEFORE INSERT OR UPDATE ON core.relation_members
  FOR EACH ROW EXECUTE FUNCTION core.catlas_relation_member_same_world();

