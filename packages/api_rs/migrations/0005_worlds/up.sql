-- Worlds are public namespaces.  Existing installations are moved into one
-- stable namespace; an empty installation intentionally remains empty.
CREATE TABLE core.worlds (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  created_by_user_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT worlds_slug_format CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  CONSTRAINT worlds_slug_length CHECK (length(slug) BETWEEN 1 AND 64),
  CONSTRAINT worlds_name_length CHECK (length(btrim(name)) BETWEEN 1 AND 128),
  CONSTRAINT worlds_created_by_user_fk FOREIGN KEY (created_by_user_id)
    REFERENCES core.users(id)
);

CREATE OR REPLACE FUNCTION core.catlas_world_slug_immutable()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.slug IS DISTINCT FROM OLD.slug THEN
    RAISE EXCEPTION 'world slug is immutable';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER worlds_slug_immutable
  BEFORE UPDATE OF slug ON core.worlds
  FOR EACH ROW EXECUTE FUNCTION core.catlas_world_slug_immutable();

ALTER TABLE core.changesets ADD COLUMN world_id bigint;
ALTER TABLE core.nodes ADD COLUMN world_id bigint;
ALTER TABLE core.ways ADD COLUMN world_id bigint;
ALTER TABLE core.relations ADD COLUMN world_id bigint;
ALTER TABLE core.way_nodes ADD COLUMN world_id bigint;
ALTER TABLE core.relation_members ADD COLUMN world_id bigint;

DO $$
DECLARE first_row record;
DECLARE default_world bigint;
BEGIN
  SELECT created_by_user_id, created_at INTO first_row
    FROM core.changesets ORDER BY id LIMIT 1;
  IF FOUND THEN
    INSERT INTO core.worlds (slug, name, created_by_user_id, created_at)
      VALUES ('default', 'Default World', first_row.created_by_user_id, first_row.created_at)
      RETURNING id INTO default_world;
    UPDATE core.changesets SET world_id = default_world;
    UPDATE core.nodes n SET world_id = c.world_id
      FROM core.changesets c WHERE c.id = n.changeset_id;
    UPDATE core.ways w SET world_id = c.world_id
      FROM core.changesets c WHERE c.id = w.changeset_id;
    UPDATE core.relations r SET world_id = c.world_id
      FROM core.changesets c WHERE c.id = r.changeset_id;
    UPDATE core.way_nodes wn SET world_id = w.world_id
      FROM core.ways w WHERE w.id = wn.way_id;
    UPDATE core.relation_members rm SET world_id = r.world_id
      FROM core.relations r WHERE r.id = rm.relation_id;
  END IF;
END $$;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM core.changesets WHERE world_id IS NULL)
     OR EXISTS (SELECT 1 FROM core.nodes WHERE world_id IS NULL)
     OR EXISTS (SELECT 1 FROM core.ways WHERE world_id IS NULL)
     OR EXISTS (SELECT 1 FROM core.relations WHERE world_id IS NULL) THEN
    RAISE EXCEPTION 'world backfill left a NULL world_id';
  END IF;
  IF EXISTS (SELECT 1 FROM core.way_nodes WHERE world_id IS NULL)
     OR EXISTS (SELECT 1 FROM core.relation_members WHERE world_id IS NULL) THEN
    RAISE EXCEPTION 'world backfill left a NULL child world_id';
  END IF;
  IF EXISTS (
    SELECT 1 FROM core.nodes n
    JOIN core.changesets created ON created.id = n.created_changeset_id
    JOIN core.changesets current ON current.id = n.changeset_id
    WHERE n.world_id <> created.world_id OR n.world_id <> current.world_id
  ) OR EXISTS (
    SELECT 1 FROM core.ways w
    JOIN core.changesets created ON created.id = w.created_changeset_id
    JOIN core.changesets current ON current.id = w.changeset_id
    WHERE w.world_id <> created.world_id OR w.world_id <> current.world_id
  ) OR EXISTS (
    SELECT 1 FROM core.relations r
    JOIN core.changesets created ON created.id = r.created_changeset_id
    JOIN core.changesets current ON current.id = r.changeset_id
    WHERE r.world_id <> created.world_id OR r.world_id <> current.world_id
  ) THEN
    RAISE EXCEPTION 'world backfill found an entity changeset mismatch';
  END IF;
  IF EXISTS (
    SELECT 1 FROM core.way_nodes wn
    JOIN core.ways w ON w.id = wn.way_id
    JOIN core.nodes n ON n.id = wn.node_id
    JOIN core.changesets c ON c.id = wn.changeset_id
    WHERE wn.world_id <> w.world_id OR wn.world_id <> n.world_id OR wn.world_id <> c.world_id
  ) OR EXISTS (
    SELECT 1 FROM core.relation_members rm
    JOIN core.relations r ON r.id = rm.relation_id
    JOIN core.changesets c ON c.id = rm.changeset_id
    WHERE rm.world_id <> r.world_id OR rm.world_id <> c.world_id
  ) THEN
    RAISE EXCEPTION 'world backfill found a child world mismatch';
  END IF;
  IF EXISTS (
    SELECT 1 FROM core.relation_members rm
    WHERE (rm.member_type = 'node' AND NOT EXISTS (
      SELECT 1 FROM core.nodes n WHERE n.id = rm.member_id AND n.world_id = rm.world_id
    )) OR (rm.member_type = 'way' AND NOT EXISTS (
      SELECT 1 FROM core.ways w WHERE w.id = rm.member_id AND w.world_id = rm.world_id
    )) OR (rm.member_type = 'relation' AND NOT EXISTS (
      SELECT 1 FROM core.relations r WHERE r.id = rm.member_id AND r.world_id = rm.world_id
    ))
  ) THEN
    RAISE EXCEPTION 'world backfill found a relation member mismatch';
  END IF;
END $$;

